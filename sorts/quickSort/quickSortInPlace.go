package main

// Временная сложность: O(N*logN)
// Пространственная сложность: O(logN) 

// Основная идея заключается в том, чтобы сортировать уже имеющийся 
// массив и не выделять память под новые подмассивы. И исходный массив 
// делится на подмассивы при помощи правильной расстановки индексов. 

// Алгоритм действий:

// 1) Выбираем опорный элемент (pivot). Обычно выбирают:
//    - последний элемент
//    - первый элемент  
//    - средний элемент
//    - медиану трех элементов (для оптимизации)

// 2) Делим массив на 3 подмассива in-place без создания новых массивов:
//    - слева элементы меньше опорного
//    - посередине элементы равные опорному (обычно 1 элемент)
//    - справа элементы больше опорного
//    Этот этап выполняется функцией partition, которая переставляет элементы
//    внутри исходного массива и возвращает индекс опорного элемента.

// 3) Применяем быструю сортировку рекурсивно к двум подмассивам:
//    - левому (элементы меньше опорного)
//    - правому (элементы больше опорного)

// 4) Так как сортировка выполняется in-place, объединение не требуется -
//    массив уже отсортирован после обработки всех подмассивов.

func QuickSortInPlace(arr []int, low, high int) []int {

	if low < high {
        // 1) Выбираем опорный элемент (в данном случае последний)
        // 2) Делим массив и получаем индекс опорного элемента
        pivotIndex := partitionInPlace(arr, low, high)
        
        // 3) Рекурсивно применяем к левому и правому подмассивам
        QuickSortInPlace(arr, low, pivotIndex-1)  // левый подмассив
        QuickSortInPlace(arr, pivotIndex+1, high) // правый подмассив
        
        // 4) Объединение не требуется - массив уже отсортирован in-place
    }
	
	return arr
}

func partitionInPlace(arr []int, low, high int) int {
	// Опорный элемент (выбираем последний)
    pivot := arr[high]
    
    // Индекс для отслеживания позиции, где будут элементы меньше опорного
    i := low - 1
    
    // Проходим по всем элементам от low до high-1
    for j := low; j < high; j++ {
        // Если текущий элемент меньше или равен опорному
        if arr[j] <= pivot {
            i++ // Увеличиваем индекс меньших элементов
            // Меняем местами элементы
            arr[i], arr[j] = arr[j], arr[i]
        }
    }
    
    // Помещаем опорный элемент на правильную позицию
    // между меньшими и большими элементами
    arr[i+1], arr[high] = arr[high], arr[i+1]
    
    // Возвращаем индекс опорного элемента
    return i + 1
}